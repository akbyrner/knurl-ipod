#!/usr/bin/env python3
"""Knurl's mark (ui/Splash.kt KnurlMark) for the boot screen: a spun-steel knob with a knurled edge,
a dark cap and one orange tick. Drawn at 4x on the boot screen's graphite, scaled down, and stored
as an opaque RGB565 square. Writes build/gen/logo.c and logo.h.
"""
import math
import sys
from pathlib import Path

from PIL import Image

SIZE = 84                      # on screen
K = 4                          # supersampling
GRAPHITE = (0x18, 0x18, 0x1B)
ORANGE = (0xFF, 0x6A, 0x1A)


def lerp(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def over(dst, src, a):
    return tuple(dst[i] + (src[i] - dst[i]) * a for i in range(3))


def hexrgb(h):
    return ((h >> 16) & 255, (h >> 8) & 255, h & 255)


SWEEP = [(0.0, hexrgb(0xECEEF1)), (0.25, hexrgb(0x8E9198)), (0.5, hexrgb(0xE4E6E9)),
         (0.75, hexrgb(0x7F8289)), (1.0, hexrgb(0xECEEF1))]


def sweep(f):
    for (t0, c0), (t1, c1) in zip(SWEEP, SWEEP[1:]):
        if f <= t1:
            return lerp(c0, c1, (f - t0) / (t1 - t0))
    return SWEEP[-1][1]


def pixel(x, y):
    """Colour at (x, y) in the mark's 200-unit space."""
    dx, dy = x - 100, y - 100
    r = math.hypot(dx, dy)
    c = GRAPHITE
    if r > 100:
        return c
    # brushed steel: a sweep gradient from 3 o'clock, clockwise, turned 110 degrees
    ang = (math.degrees(math.atan2(dy, dx)) - 110) % 360
    c = sweep(ang / 360)
    # the knurled edge: ridges 2.2 long every 8.1 round a circle of radius 93, 9 wide
    if abs(r - 93) <= 4.5:
        along = (math.atan2(dy, dx) % (2 * math.pi)) * 93
        if along % 8.1 < 2.2:
            c = over(c, (0x2A, 0x2B, 0x30), 0.45)
    if abs(r - 86.5) <= 0.5:
        c = over(c, (255, 255, 255), 0.35)
    # the cap
    if r <= 40:
        t = min(1.0, math.hypot(x - 100, y - 70) / 140)
        c = lerp(hexrgb(0x3A3A40), hexrgb(0x121214), t)
    if 39 <= r <= 41:
        t = min(1.0, max(0.0, (y - 60) / 80))
        c = over(c, (0, 0, 0), 0.55 * (1 - t)) if t < 0.5 else over(c, (255, 255, 255), 0.5 * t)
    # the tick
    if 97 <= x <= 103 and 15 <= y <= 43:
        cy = min(max(y, 18), 40)
        if math.hypot(x - 100, y - cy) <= 3 or 18 <= y <= 40:
            c = ORANGE
    return c


def main(out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    big = SIZE * K
    img = Image.new("RGB", (big, big))
    px = img.load()
    for j in range(big):
        for i in range(big):
            px[i, j] = tuple(round(v) for v in pixel((i + 0.5) * 200 / big, (j + 0.5) * 200 / big))
    img = img.resize((SIZE, SIZE), Image.LANCZOS)
    data = []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = img.getpixel((x, y))
            data.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    lines = ["/* Generated by tools/build_logo.py - do not edit. */", '#include "logo.h"',
             f"const uint16_t logo_px[{SIZE * SIZE}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{v:04X}" for v in data[i:i + 16]) + ",")
    lines.append("};")
    (out / "logo.c").write_text("\n".join(lines) + "\n")
    (out / "logo.h").write_text("/* Generated by tools/build_logo.py */\n#pragma once\n#include <stdint.h>\n"
                                f"#define LOGO_S {SIZE}\nextern const uint16_t logo_px[{SIZE * SIZE}];\n")
    print(f"logo: {SIZE}x{SIZE}")


if __name__ == "__main__":
    main(sys.argv[1])
