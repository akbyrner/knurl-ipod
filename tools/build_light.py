#!/usr/bin/env python3
"""The plane's light-and-grain layer as one 320x240 alpha table (0..255), from ui/Plane.kt:
a radial white light (7% at the top centre, gone at 0.9 x screen width) and Knurl's grain
(white at 0..18/255, a 128x128 random tile). The firmware lays it over every plane.
Writes build/gen/light.c and light.h.
"""
import math
import random
import sys
from pathlib import Path

W, H = 320, 240


def main(out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rnd = random.Random(7)
    tile = [rnd.randint(0, 18) for _ in range(128 * 128)]
    data = bytearray()
    for y in range(H):
        for x in range(W):
            d = math.hypot(x - W / 2, y) / (W * 0.9)
            light = max(0.0, 1 - d) * 0.07
            grain = tile[(y % 128) * 128 + (x % 128)] / 255
            a = 1 - (1 - light) * (1 - grain)
            data.append(min(255, round(a * 256)))
    lines = ["/* Generated by tools/build_light.py - do not edit. */", '#include "light.h"',
             f"const uint8_t light_alpha[{W * H}] = {{"]
    for i in range(0, len(data), 32):
        lines.append("    " + ",".join(map(str, data[i:i + 32])) + ",")
    lines.append("};")
    (out / "light.c").write_text("\n".join(lines) + "\n")
    (out / "light.h").write_text("/* Generated by tools/build_light.py */\n#pragma once\n#include <stdint.h>\n"
                                 f"extern const uint8_t light_alpha[{W * H}];\n")
    print(f"light: {len(data)} bytes")


if __name__ == "__main__":
    main(sys.argv[1])
