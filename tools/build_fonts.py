#!/usr/bin/env python3
"""Rasterise Knurl's fonts into 4-bit anti-aliased glyph sheets for the firmware.

Writes build/gen/fonts.c and build/gen/fonts.h. Each font is one size of one face; the
iPod only ever draws these exact sizes, so there's no font engine on the device: a glyph
is a small alpha bitmap blended into the framebuffer.

Character set: printable ASCII, Latin-1 and common typographic punctuation. (Later the
server will add exactly the characters that occur in the library, in any script.)
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parent.parent / "assets" / "fonts"

# name, file, pixel size, variable-font axes, purpose
FACES = [
    ("font_title",  "archivo.ttf",          20, {"wght": 800, "wdth": 125}, "screen titles (wide caps)"),
    ("font_row",    "inter.ttf",            13, {"wght": 600},              "list rows"),
    ("font_body",   "inter.ttf",            11, {"wght": 500},              "secondary text"),
    ("font_strong", "inter.ttf",            12, {"wght": 650},              "mini player title"),
    ("font_letter", "inter.ttf",            16, {"wght": 750},              "letter tiles"),
    ("font_mono",   "plex_mono_medium.ttf",  9, {},                         "engraved caps labels"),
    ("font_mono_s", "plex_mono_medium.ttf",  8, {},                         "times, small labels"),
    ("font_brand",  "archivo.ttf",          32, {"wght": 800, "wdth": 125}, "the KNURL word on the boot screen"),
]

CHARSET = sorted(set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) |
                 {0x2018, 0x2019, 0x201C, 0x201D, 0x2013, 0x2014, 0x2022, 0x00B7, 0x2026, 0x2032, 0x2033})
# Faces that only ever draw a few letters carry just those.
FACE_CHARS = {"font_brand": sorted({ord(c) for c in "KNURL"})}   # sorted: glyphs are looked up by code point


def load(file, size, axes):
    f = ImageFont.truetype(str(FONTS / file), size)
    if axes:
        try:
            values = []
            for a in f.get_variation_axes():
                name = a["name"].decode() if isinstance(a["name"], bytes) else a["name"]
                key = {"Weight": "wght", "Width": "wdth", "Optical size": "opsz"}.get(name, name)
                values.append(axes.get(key, a["default"]))
            f.set_variation_by_axes(values)
        except OSError:
            pass
    return f


def raster(font, ch):
    """Returns (advance, xoff, yoff, w, h, 4-bit alpha rows) with yoff from the top of the line box."""
    ascent, descent = font.getmetrics()
    adv = round(font.getlength(ch))
    box = font.getbbox(ch, anchor="ls")  # relative to the baseline
    if box[2] <= box[0] or box[3] <= box[1]:
        return adv, 0, 0, 0, 0, []
    w, h = box[2] - box[0], box[3] - box[1]
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
    rows = [[(img.getpixel((x, y)) * 15 + 127) // 255 for x in range(w)] for y in range(h)]
    return adv, box[0], ascent + box[1], w, h, rows


def main(out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    c = ['/* Generated by tools/build_fonts.py - do not edit. */', '#include "fonts.h"', '']
    h = ['/* Generated by tools/build_fonts.py - do not edit. */', '#pragma once', '#include "gfx/font.h"', '']
    total = 0
    for name, file, size, axes, purpose in FACES:
        font = load(file, size, axes)
        ascent, descent = font.getmetrics()
        glyphs, data = [], bytearray()
        for cp in FACE_CHARS.get(name, CHARSET):
            ch = chr(cp)
            if font.getmask(ch).getbbox() is None and ch != " " and cp != 0xA0:
                continue  # not in this font
            adv, xo, yo, w, gh, rows = raster(font, ch)
            off = len(data)
            for r in rows:  # pack two 4-bit pixels per byte, rows padded to a whole byte
                for i in range(0, w, 2):
                    a = r[i]
                    b = r[i + 1] if i + 1 < w else 0
                    data.append((a << 4) | b)
            glyphs.append((cp, xo, yo, w, gh, adv, off))
        c.append(f"/* {name}: {file} {size}px {axes} - {purpose} */")
        c.append(f"static const uint8_t {name}_bits[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            c.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        if not data:
            c.append("    0,")
        c.append("};")
        c.append(f"static const glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for g in glyphs:
            c.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
        c.append("};")
        c.append(f"const font_t {name} = {{ {name}_glyphs, {len(glyphs)}, {name}_bits, {ascent}, {ascent + descent} }};")
        c.append("")
        h.append(f"extern const font_t {name};  /* {purpose}: {size}px */")
        total += len(data) + len(glyphs) * 12
    (out / "fonts.c").write_text("\n".join(c) + "\n")
    (out / "fonts.h").write_text("\n".join(h) + "\n")
    print(f"fonts: {len(FACES)} faces, ~{total // 1024} KB")


if __name__ == "__main__":
    main(sys.argv[1])
