#!/usr/bin/env python3
"""x^(4/3) for every value a Layer III Huffman code can produce (0..8206 = 15 + 2^13 - 1),
for the fixed-point MP3 decoder (firmware/src/mp3). Packed as (mantissa << 5) | exponent with
x^(4/3) = mantissa * 2^(exponent - 26), mantissa normalised to [2^26, 2^27)."""
import math, sys, os
N = 8207
vals = [0]
for x in range(1, N):
    v = x ** (4.0 / 3.0)
    e = math.floor(math.log2(v))
    m = round(v * 2.0 ** (26 - e))
    if m >= 1 << 27:
        m >>= 1; e += 1
    assert (1 << 26) <= m < (1 << 27) and 0 <= e < 32
    vals.append((m << 5) | e)
out = os.path.join(sys.argv[1], "pow43.c")
with open(out, "w") as f:
    f.write("/* generated by tools/build_pow43.py */\n#include <stdint.h>\n")
    f.write("const uint32_t mp3_pow43[%d] = {\n" % N)
    for i in range(0, N, 8):
        f.write("    " + ", ".join("0x%08x" % v for v in vals[i:i + 8]) + ",\n")
    f.write("};\n")
